// ─── Round constants ────────────────────────────────────────────────────────

const RCON = [
  0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36
];

// ─── GF(2^8) multiplication ─────────────────────────────────────────────────

function gmul(a, b) {
  let p = 0;
  for (let i = 0; i < 8; i++) {
    if (b & 1) p ^= a;
    const hi = a & 0x80;
    a = (a << 1) & 0xff;
    if (hi) a ^= 0x1b; // irreducible polynomial x^8 + x^4 + x^3 + x + 1
    b >>= 1;
  }
  return p;
}

// ─── Key Expansion ──────────────────────────────────────────────────────────

function keyExpansion(key) {
  // key is 16 bytes → 11 round keys (44 words)
  const w = new Uint32Array(44);

  // First 4 words from key
  for (let i = 0; i < 4; i++) {
    w[i] = (key[4*i] << 24) | (key[4*i+1] << 16) | (key[4*i+2] << 8) | key[4*i+3];
  }

  for (let i = 4; i < 44; i++) {
    let temp = w[i - 1];
    if (i % 4 === 0) {
      // RotWord
      temp = ((temp << 8) | (temp >>> 24)) >>> 0;
      // SubWord
      temp = (SBOX[(temp >>> 24) & 0xff] << 24) |
             (SBOX[(temp >>> 16) & 0xff] << 16) |
             (SBOX[(temp >>> 8) & 0xff] << 8) |
             SBOX[temp & 0xff];
      temp = (temp ^ (RCON[i/4 - 1] << 24)) >>> 0;
    }
    w[i] = (w[i - 4] ^ temp) >>> 0;
  }

  // Convert to byte arrays (11 round keys of 16 bytes each)
  const roundKeys = [];
  for (let r = 0; r < 11; r++) {
    const rk = new Uint8Array(16);
    for (let j = 0; j < 4; j++) {
      rk[4*j]   = (w[4*r + j] >>> 24) & 0xff;
      rk[4*j+1] = (w[4*r + j] >>> 16) & 0xff;
      rk[4*j+2] = (w[4*r + j] >>> 8) & 0xff;
      rk[4*j+3] =  w[4*r + j] & 0xff;
    }
    roundKeys.push(rk);
  }
  return roundKeys;
}

// ─── AES internal operations (state is 4x4 column-major) ───────────────────

function subBytes(state) {
  for (let i = 0; i < 16; i++) state[i] = SBOX[state[i]];
}

function invSubBytes(state) {
  for (let i = 0; i < 16; i++) state[i] = INV_SBOX[state[i]];
}

function shiftRows(state) {
  // Row 1: shift left 1
  let t = state[1];
  state[1] = state[5]; state[5] = state[9]; state[9] = state[13]; state[13] = t;
  // Row 2: shift left 2
  t = state[2]; state[2] = state[10]; state[10] = t;
  t = state[6]; state[6] = state[14]; state[14] = t;
  // Row 3: shift left 3 (= right 1)
  t = state[15];
  state[15] = state[11]; state[11] = state[7]; state[7] = state[3]; state[3] = t;
}

function invShiftRows(state) {
  // Row 1: shift right 1
  let t = state[13];
  state[13] = state[9]; state[9] = state[5]; state[5] = state[1]; state[1] = t;
  // Row 2: shift right 2
  t = state[2]; state[2] = state[10]; state[10] = t;
  t = state[6]; state[6] = state[14]; state[14] = t;
  // Row 3: shift right 3 (= left 1)
  t = state[3];
  state[3] = state[7]; state[7] = state[11]; state[11] = state[15]; state[15] = t;
}

function mixColumns(state) {
  for (let c = 0; c < 4; c++) {
    const i = c * 4;
    const s0 = state[i], s1 = state[i+1], s2 = state[i+2], s3 = state[i+3];
    state[i]   = gmul(2,s0) ^ gmul(3,s1) ^ s2        ^ s3;
    state[i+1] = s0         ^ gmul(2,s1) ^ gmul(3,s2) ^ s3;
    state[i+2] = s0         ^ s1         ^ gmul(2,s2) ^ gmul(3,s3);
    state[i+3] = gmul(3,s0) ^ s1         ^ s2         ^ gmul(2,s3);
  }
}

function invMixColumns(state) {
  for (let c = 0; c < 4; c++) {
    const i = c * 4;
    const s0 = state[i], s1 = state[i+1], s2 = state[i+2], s3 = state[i+3];
    state[i]   = gmul(14,s0) ^ gmul(11,s1) ^ gmul(13,s2) ^ gmul(9,s3);
    state[i+1] = gmul(9,s0)  ^ gmul(14,s1) ^ gmul(11,s2) ^ gmul(13,s3);
    state[i+2] = gmul(13,s0) ^ gmul(9,s1)  ^ gmul(14,s2) ^ gmul(11,s3);
    state[i+3] = gmul(11,s0) ^ gmul(13,s1) ^ gmul(9,s2)  ^ gmul(14,s3);
  }
}

function addRoundKey(state, roundKey) {
  for (let i = 0; i < 16; i++) state[i] ^= roundKey[i];
}

// ─── Public API ─────────────────────────────────────────────────────────────

/**
 * Encrypt a single 16-byte block with AES-128.
 * @param {Uint8Array} key   - 16-byte key
 * @param {Uint8Array} block - 16-byte plaintext block
 * @returns {Uint8Array}     - 16-byte ciphertext block
 */
export function aesEncryptBlock(key, block) {
  const roundKeys = keyExpansion(key);
  // State is column-major: state[col*4 + row]
  const state = new Uint8Array(16);
  for (let r = 0; r < 4; r++) {
    for (let c = 0; c < 4; c++) {
      state[c * 4 + r] = block[r * 4 + c];
    }
  }

  addRoundKey(state, roundKeys[0]);

  for (let round = 1; round <= 9; round++) {
    subBytes(state);
    shiftRows(state);
    mixColumns(state);
    addRoundKey(state, roundKeys[round]);
  }

  // Last round (no MixColumns)
  subBytes(state);
  shiftRows(state);
  addRoundKey(state, roundKeys[10]);

  // Convert back to row-major
  const output = new Uint8Array(16);
  for (let r = 0; r < 4; r++) {
    for (let c = 0; c < 4; c++) {
      output[r * 4 + c] = state[c * 4 + r];
    }
  }
  return output;
}

/**
 * Decrypt a single 16-byte block with AES-128.
 * @param {Uint8Array} key   - 16-byte key
 * @param {Uint8Array} block - 16-byte ciphertext block
 * @returns {Uint8Array}     - 16-byte plaintext block
 */
export function aesDecryptBlock(key, block) {
  const roundKeys = keyExpansion(key);
  const state = new Uint8Array(16);
  for (let r = 0; r < 4; r++) {
    for (let c = 0; c < 4; c++) {
      state[c * 4 + r] = block[r * 4 + c];
    }
  }

  addRoundKey(state, roundKeys[10]);

  for (let round = 9; round >= 1; round--) {
    invShiftRows(state);
    invSubBytes(state);
    addRoundKey(state, roundKeys[round]);
    invMixColumns(state);
  }

  invShiftRows(state);
  invSubBytes(state);
  addRoundKey(state, roundKeys[0]);

  const output = new Uint8Array(16);
  for (let r = 0; r < 4; r++) {
    for (let c = 0; c < 4; c++) {
      output[r * 4 + c] = state[c * 4 + r];
    }
  }
  return output;
}

/**
 * Use AES as a PRF: F_k(x) = AES_k(x).
 * @param {Uint8Array} key   - 16-byte key
 * @param {Uint8Array} input - 16-byte input
 * @returns {Uint8Array}     - 16-byte output
 */
export function aesPRF(key, input) {
  return aesEncryptBlock(key, input);
}

